import assert from 'node:assert/strict';
import {availableRounds,penetrationAt,armorPlate,resolveArmorHit} from '../app/src/main/assets/ballistics.js';
const t=availableRounds('T-34-85'),p=availableRounds('Panzer III');
assert.deepEqual(t.map(x=>x.id),['BR-365K','O-365K','BR-365','BR-365P']);
assert.deepEqual(p.map(x=>x.id),['PzGr 39','Sprgr. 38','PzGr 40/1','PzGr 40']);
assert.equal(penetrationAt(10,t[0]),148);
assert.equal(penetrationAt(1000,t[0]),106);
assert.equal(penetrationAt(300,t[0]),134.5);
assert.equal(penetrationAt(1000,p[0]),65);
assert.equal(armorPlate('T-34-85',[0,1.6,-2],[0,0,1]).mm,45);
assert.equal(armorPlate('T-34-85',[1.6,1.5,0],[-1,0,0]).mm,45);
assert.equal(armorPlate('Panzer III',[1.6,1.5,0],[-1,0,0]).mm,30);
assert.equal(armorPlate('T-34-85',[0,2.3,-1],[0,0,1]).mm,90);
let dmg=[];
const hit=(vehicle,point,direction,round,distance)=>resolveArmorHit({targetName:vehicle,hit:point,direction,distance,round,damageModule:(key,amount)=>dmg.push([key,amount])});
const x=hit('Panzer III',[0,1.45,-2.25],[0,0,1],t[0],10);
assert.equal(x.pierced,true);assert.ok(x.eff>50);assert.ok(dmg.some(x=>x[0]==='driver'));
dmg=[];
const y=hit('T-34-85',[0,1.5,-2.3],[0,0,1],p[1],10);assert.equal(y.pierced,false);assert.equal(y.overpressure,undefined);assert.equal(dmg.length,0);
dmg=[];
const z=hit('Panzer III',[0,2.8,-.1],[0,-1,0],t[1],10);
assert.equal(z.pierced,true);assert.ok(z.overpressure);assert.ok(dmg.length>0);
const a=availableRounds('Abrams (Freeciv)');assert.equal(a.length,3);
assert.equal(penetrationAt(1200,a[1]),220);
console.log('11 armor/shell checks passed + module/no-overpressure, blast-overpressure checks',x,z);